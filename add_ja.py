def main():
    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)

    # categories
    for c in data.get("categories", []):
        slug = c.get("slug")
        if slug in CAT_JA:
            c["labelJa"] = CAT_JA[slug]

    missing = []
    for loop in data["loops"]:
        num = loop["number"]
        if num not in JA:
            missing.append(num)
            continue
        title_ja, desc_ja, when_ja = JA[num]
        loop["titleJa"] = title_ja
        loop["descriptionJa"] = desc_ja
        loop["useWhenJa"] = when_ja
        # embedded category label
        cslug = loop["category"].get("slug")
        if cslug in CAT_JA:
            loop["category"]["labelJa"] = CAT_JA[cslug]

    if missing:
        print("WARNING: 未翻訳の番号:", missing)
        raise SystemExit(1)

    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print("OK: %d loops translated, %d categories labeled" % (len(data["loops"]), len(data.get("categories", []))))


if __name__ == "__main__":
    main()
